package gen

import (
	"fmt"
	"maps"
	"slices"
	"strings"
	"unicode"
)

const goTypeNameExtension = "x-go-type-name"

// NameInlineObjects gives every inline object schema that has properties a stable x-go-type-name
// derived from where it sits (Error.details becomes ErrorDetails), so oapi-codegen emits a named
// type instead of an anonymous struct. A named type can gain a field later without an incompatible
// change to package generated; an anonymous one cannot. The spec is changed in place and the names
// it assigned are returned, sorted. A name that another schema, another inline object or a type
// oapi-codegen derives from an operation already holds is an error: guessing would hide it.
func NameInlineObjects(spec map[string]any) ([]string, error) {
	namer := &inlineNamer{used: map[string]string{}}
	components, _ := spec["components"].(map[string]any)
	schemas, _ := components["schemas"].(map[string]any)
	for _, name := range slices.Sorted(maps.Keys(schemas)) {
		if err := namer.reserve(pascal(name), "components.schemas."+name); err != nil {
			return nil, err
		}
	}
	for _, name := range slices.Sorted(maps.Keys(schemas)) {
		schema, err := asObject(schemas[name], "components.schemas."+name)
		if err != nil {
			return nil, err
		}
		if err := namer.children(schema, pascal(name), "components.schemas."+name); err != nil {
			return nil, err
		}
	}
	paths, err := asObject(spec["paths"], "paths")
	if err != nil {
		return nil, err
	}
	for _, path := range slices.Sorted(maps.Keys(paths)) {
		item, itemErr := asObject(paths[path], "paths."+path)
		if itemErr != nil {
			return nil, itemErr
		}
		for _, method := range httpMethods {
			raw, present := item[method]
			if !present {
				continue
			}
			operation, operationErr := asObject(raw, method+" "+path)
			if operationErr != nil {
				return nil, operationErr
			}
			if err := namer.operation(operation, strings.ToUpper(method)+" "+path); err != nil {
				return nil, err
			}
		}
	}
	return slices.Sorted(maps.Keys(namer.assigned)), nil
}

type inlineNamer struct {
	used     map[string]string
	assigned map[string]string
}

func (n *inlineNamer) reserve(name, where string) error {
	if other, taken := n.used[name]; taken {
		return fmt.Errorf("the type name %s is wanted by both %s and %s", name, other, where)
	}
	n.used[name] = where
	return nil
}

func (n *inlineNamer) assign(name, where string) error {
	if err := n.reserve(name, where); err != nil {
		return err
	}
	if n.assigned == nil {
		n.assigned = map[string]string{}
	}
	n.assigned[name] = where
	return nil
}

// operation names the inline objects in one operation's parameters, request body and responses.
// oapi-codegen itself names a top-level inline request body <Operation>JSONBody, so only the
// objects inside it are named here; a top-level inline response body is named <Operation>Result
// (<Operation>Result<status> for any status but 200).
func (n *inlineNamer) operation(operation map[string]any, where string) error {
	id, hasID := operation["operationId"].(string)
	if !hasID || id == "" {
		return nil
	}
	base := pascal(id)
	for _, suffix := range []string{"Response", "Params", "JSONBody", "JSONRequestBody"} {
		if err := n.reserve(base+suffix, where+" (generated by oapi-codegen)"); err != nil {
			return err
		}
	}
	parameters, _ := operation["parameters"].([]any)
	for _, raw := range parameters {
		parameter, _ := raw.(map[string]any)
		schema, _ := parameter["schema"].(map[string]any)
		name, _ := parameter["name"].(string)
		if schema == nil || name == "" {
			continue
		}
		if err := n.visit(schema, base+pascal(name), where+" parameter "+name); err != nil {
			return err
		}
	}
	body, _ := operation["requestBody"].(map[string]any)
	if err := n.content(body["content"], base+"Request", false, where+" request"); err != nil {
		return err
	}
	responses, _ := operation["responses"].(map[string]any)
	for _, status := range slices.Sorted(maps.Keys(responses)) {
		response, _ := responses[status].(map[string]any)
		name := base + "Result"
		if status != "200" {
			name += pascal(status)
		}
		if err := n.content(response["content"], name, true, where+" response "+status); err != nil {
			return err
		}
	}
	return nil
}

func (n *inlineNamer) content(content any, name string, nameTop bool, where string) error {
	media, _ := content.(map[string]any)
	for _, kind := range slices.Sorted(maps.Keys(media)) {
		entry, _ := media[kind].(map[string]any)
		schema, _ := entry["schema"].(map[string]any)
		if schema == nil {
			continue
		}
		if nameTop {
			if err := n.visit(schema, name, where+" "+kind); err != nil {
				return err
			}
		} else if err := n.children(schema, name, where+" "+kind); err != nil {
			return err
		}
	}
	return nil
}

// visit names the schema when it is an inline object and then descends into it.
func (n *inlineNamer) visit(schema map[string]any, name, where string) error {
	if _, isReference := schema["$ref"]; isReference {
		return nil
	}
	if _, isObject := schema["properties"]; isObject {
		if existing, named := schema[goTypeNameExtension].(string); named {
			name = existing
		} else {
			schema[goTypeNameExtension] = name
		}
		if err := n.assign(name, where); err != nil {
			return err
		}
	}
	return n.children(schema, name, where)
}

// children descends into the sub-schemas of schema, which is named name (or is the unnamed top of
// an operation body, where name is only the prefix for what it holds).
func (n *inlineNamer) children(schema map[string]any, name, where string) error {
	properties, _ := schema["properties"].(map[string]any)
	for _, key := range slices.Sorted(maps.Keys(properties)) {
		child, _ := properties[key].(map[string]any)
		if child == nil {
			continue
		}
		if err := n.visit(child, name+pascal(key), where+"."+key); err != nil {
			return err
		}
	}
	if items, _ := schema["items"].(map[string]any); items != nil {
		if err := n.visit(items, singular(name), where+"[]"); err != nil {
			return err
		}
	}
	if extra, _ := schema["additionalProperties"].(map[string]any); extra != nil {
		if err := n.visit(extra, name+"Value", where+"{}"); err != nil {
			return err
		}
	}
	for _, keyword := range []string{"allOf", "anyOf", "oneOf"} {
		members, _ := schema[keyword].([]any)
		objects := 0
		for _, raw := range members {
			if member, _ := raw.(map[string]any); member != nil {
				if _, isObject := member["properties"]; isObject {
					objects++
				}
			}
		}
		for index, raw := range members {
			member, _ := raw.(map[string]any)
			if member == nil {
				continue
			}
			memberName := name
			if objects > 1 {
				memberName = fmt.Sprintf("%sVariant%d", name, index+1)
			}
			if err := n.visit(member, memberName, fmt.Sprintf("%s.%s[%d]", where, keyword, index)); err != nil {
				return err
			}
		}
	}
	return nil
}

// pascal turns a schema, property or operation name into an exported Go identifier part:
// create_upload becomes CreateUpload, and capitals inside a word are kept.
func pascal(text string) string {
	var out strings.Builder
	upper := true
	for _, r := range text {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		out.WriteRune(r)
	}
	return out.String()
}

// singular names the element of an array: Parts becomes Part, anything else gains Item.
func singular(name string) string {
	if stripped, found := strings.CutSuffix(name, "s"); found && !strings.HasSuffix(stripped, "s") {
		return stripped
	}
	return name + "Item"
}
